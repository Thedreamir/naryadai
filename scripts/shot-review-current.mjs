import {chromium} from 'playwright'
const b=await chromium.launch()
const pg=await (await b.newContext({viewport:{width:1440,height:900}})).newPage()
await pg.goto('http://127.0.0.1:4173/login')
await pg.fill('input[type=email]','master@naryadai.test'); await pg.fill('input[type=password]',process.env.PW_MASTER)
await pg.click('button:has-text("Войти")')
await pg.waitForSelector('a[href="/report"]',{timeout:30000}).catch(()=>{})
await pg.goto('http://127.0.0.1:4173/report',{waitUntil:'networkidle'}).catch(()=>{})
await pg.waitForSelector('text=Аномалии и рекомендации',{timeout:30000}).catch(()=>{})
await pg.waitForSelector('rect.recharts-rectangle',{timeout:20000}).catch(()=>{})
await pg.waitForTimeout(2500)
await pg.screenshot({path:'/tmp/b789-report-top.png'})
await pg.evaluate(()=>window.scrollTo(0,1200))
await pg.waitForTimeout(800)
await pg.screenshot({path:'/tmp/b789-report-anomalies.png'})
await pg.context().close()
const pg2=await (await b.newContext({viewport:{width:430,height:932}})).newPage()
await pg2.goto('http://127.0.0.1:4173/login')
await pg2.fill('input[type=email]','worker-a@naryadai.test'); await pg2.fill('input[type=password]',process.env.PW_WORKERA)
await pg2.click('button:has-text("Войти")')
await pg2.waitForSelector('a[href="/profile"]',{timeout:30000})
await pg2.goto('http://127.0.0.1:4173/profile',{waitUntil:'networkidle'}).catch(()=>{})
await pg2.waitForSelector('text=Посчитано факторов',{timeout:30000})
await pg2.screenshot({path:'/tmp/b789-profile.png'})
await b.close(); console.log('done')
