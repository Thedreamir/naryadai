import {chromium} from '@playwright/test'
const b=await chromium.launch()
const pg=await (await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true})).newPage()
await pg.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'})
await pg.fill('input[type=email]','worker-a@naryadai.test')
await pg.fill('input[type=password]',process.env.PW_WORKERA)
await pg.click('button:has-text("Войти")'); await pg.waitForTimeout(7000)
await pg.evaluate(()=>{const p=JSON.parse(localStorage.getItem('tk-prefs')||'{}');p.theme='light';localStorage.setItem('tk-prefs',JSON.stringify(p))})
await pg.goto('http://127.0.0.1:4173/orders/532'); await pg.waitForTimeout(2500)
await pg.click('button:has-text("Сдать наряд")'); await pg.waitForTimeout(800)
await pg.screenshot({path:'/tmp/v10-10-light-wizard1.png'})
const cbs=pg.locator('.fixed input[type=checkbox]')
for(let i=0;i<await cbs.count();i++) await cbs.nth(i).click()
await pg.click('button:has-text("Далее")'); await pg.waitForTimeout(500)
await pg.screenshot({path:'/tmp/v10-11-light-wizard2.png'})
await b.close(); console.log('done')
