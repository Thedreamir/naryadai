import {chromium} from 'playwright'
const b=await chromium.launch()
const pg=await (await b.newContext({viewport:{width:1440,height:900}})).newPage()
await pg.goto('http://127.0.0.1:4173/login')
await pg.fill('input[type=email]','master@naryadai.test'); await pg.fill('input[type=password]',process.env.PW_MASTER)
await pg.click('button:has-text("Войти")')
await pg.waitForSelector('a[href^="/orders/"]',{timeout:30000}).catch(()=>{})
await pg.waitForTimeout(4000)
await pg.screenshot({path:'/tmp/e10-10-mst-board.png'})
for(const [path,name] of [['/review','11-mst-review'],['/issue','12-mst-issue'],['/closed','13-mst-closed'],['/handover','14-mst-handover'],['/report','15-mst-report']]){
  await pg.goto('http://127.0.0.1:4173'+path,{waitUntil:'networkidle'}).catch(()=>{})
  await pg.waitForTimeout(5000)
  await pg.screenshot({path:`/tmp/e10-${name}.png`})
}
await pg.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'}).catch(()=>{})
const ml=pg.locator('a[href^="/orders/"]').first()
if(await ml.count()){await ml.click(); await pg.waitForTimeout(4000); await pg.screenshot({path:'/tmp/e10-16-mst-orderdetail.png'})}
await pg.context().close()
const pg2=await (await b.newContext({viewport:{width:1440,height:900}})).newPage()
await pg2.goto('http://127.0.0.1:4173/login')
await pg2.fill('input[type=email]','leader@naryadai.test'); await pg2.fill('input[type=password]',process.env.PW_LEADER)
await pg2.click('button:has-text("Войти")')
await pg2.waitForTimeout(8000)
await pg2.screenshot({path:'/tmp/e10-20-leader.png'})
await b.close(); console.log('master/leader done')
