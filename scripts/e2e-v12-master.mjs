import {createClient} from '@supabase/supabase-js'
const s=createClient(process.env.SUPABASE_URL,process.env.SB_ANON)
await s.auth.signInWithPassword({email:'master@naryadai.test',password:process.env.PW_MASTER})
const {data:o}=await s.from('orders').select('id,status,version').eq('id',650).single()
console.log('before:',JSON.stringify(o))
const {data:rev,error:e1}=await s.functions.invoke('review-order',{body:{id:650,version:o.version}})
console.log(e1?('REVIEW ERR '+String(e1).slice(0,150)):('review: '+JSON.stringify(rev?.result?.verdict)+' mode='+(rev?.result?.mode||rev?.result?.result?.mode)))
const {data:o2}=await s.from('orders').select('id,status,version').eq('id',650).single()
console.log('after review:',JSON.stringify(o2))
const {data,error:e2}=await s.rpc('transition_order',{order_id:650,target_status:'closed',expected_version:o2.version,reason_text:'',closure_data:null,human_score:5,human_comment:'E2E приёмка'})
console.log(e2?('CLOSE ERR '+e2.message):'closed OK')
await s.auth.signOut()
